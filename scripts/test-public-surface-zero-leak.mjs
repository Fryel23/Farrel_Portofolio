// Additional strict rules for /aethelgrad files and built /aethelgrad/index.html
const AETHELGRAD_STRICT_FORBIDDEN = [
  { label: 'word "update/updated/updating" in Aethelgrad UI', regex: /\b(?:update|updated|updating)\b/gi },
  { label: 'word "version" in Aethelgrad UI', regex: /\bversion\b/gi },
  { label: 'word "release / patch" in Aethelgrad UI', regex: /\b(?:release|patch)\b/gi },
  { label: 'word "build" in Aethelgrad UI', regex: /\bbuild\b/gi },
  { label: 'word "test / tests / passing / lulus / coverage" in Aethelgrad UI', regex: /\b(?:test|tests|passing|lulus|coverage)\b/gi },
  { label: 'word "audit / parity / QA" in Aethelgrad UI', regex: /\b(?:audit|parity|QA)\b/g },
  { label: 'word "preview" in Aethelgrad UI', regex: /\bpreview\b/gi },
  { label: 'word "agent / executor / prompt / specification / dokumen" in Aethelgrad UI', regex: /\b(?:agent|executor|prompt|specification|dokumen)\b/gi },
  { label: 'word "Git / GitHub / commit / push / deploy / deployment / remote / snapshot" in Aethelgrad UI', regex: /\b(?:Git|GitHub|commit|push|deploy|deployment|remote|snapshot)\b/g },
];

function extractHumanVisibleFromCode(raw, relPath) {
  if (relPath.endsWith('.html') || relPath.endsWith('.astro') || relPath.endsWith('.md') || relPath.endsWith('.svg')) {
    let cleaned = prepareScannableText(raw, relPath);
    if (relPath.endsWith('.astro')) {
      // Remove import lines and JS code identifiers in frontmatter, but keep string literals and template markup
      cleaned = cleaned.replace(/^import\s+.*$/gm, '');
      // Remove inline <script> blocks' JS syntax tokens like .update() or DOM API while keeping string literals
    }
    return cleaned;
  }
  if (relPath.endsWith('.ts') || relPath.endsWith('.js') || relPath.endsWith('.mjs')) {
    // Extract string literals (single, double, template) and comments
    const matches = [];
    const tokenRegex = /\/\/[^\n]*|\/\*[\s\S]*?\*\/|'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`/g;
    let m;
    while ((m = tokenRegex.exec(raw)) !== null) {
      const token = m[0];
      // Ignore pure CSS selector/DOM event/path tokens
      if (/^['"][#./a-z0-9_-]+['"]$/i.test(token)) continue;
      matches.push(token);
    }
    return matches.join('\n');
  }
  return raw;
}

const targetDirs = [
  path.join(ROOT, 'src/pages'),
  path.join(ROOT, 'src/components'),
  path.join(ROOT, 'src/layouts'),
  path.join(ROOT, 'src/world-aethelgrad'),
  path.join(ROOT, 'public'),
];

if (includeDist) {
  const distDir = path.join(ROOT, 'dist');
  if (!fs.existsSync(distDir)) {
    console.error('[FAIL] --dist specified but dist/ directory does not exist.');
    process.exit(1);
  }
  targetDirs.push(distDir);
}

const files = [];
for (const dir of targetDirs) {
  walkDir(dir, files);
}

const violations = [];

for (const filePath of files) {
  const relPath = path.relative(ROOT, filePath).replace(/\\/g, '/');
  // Skip binary or font metadata or third-party chart bundle in dist/_astro
  if (relPath.startsWith('dist/_astro/') && !relPath.includes('aethelgrad') && !relPath.includes('index')) {
    // Still check em-dash and universal process leaks in our own bundles, skip third-party chart.js vendor chunk
    const base = path.basename(relPath);
    if (base.startsWith('chart') || base.startsWith('auto')) continue;
  }

  const raw = fs.readFileSync(filePath, 'utf8');
  const scannable = prepareScannableText(raw, relPath);

  for (const rule of UNIVERSAL_FORBIDDEN) {
    rule.regex.lastIndex = 0;
    const match = rule.regex.exec(scannable);
    if (match) {
      violations.push({
        file: relPath,
        rule: rule.label,
        sample: match[0],
      });
    }
  }

  const isAethelgradSurface =
    relPath.includes('aethelgrad') &&
    !relPath.startsWith('src/world-aethelgrad/server/') &&
    !relPath.startsWith('dist/_astro/');

  if (isAethelgradSurface) {
    let humanText = extractHumanVisibleFromCode(raw, relPath);
    // Strip JS method calls like .push(...) or .test(...) inside algorithm snippets
    humanText = humanText.replace(/\.\s*(?:push|test)\s*\(/g, '.call(');
    for (const rule of AETHELGRAD_STRICT_FORBIDDEN) {
      rule.regex.lastIndex = 0;
      const match = rule.regex.exec(humanText);
      if (match) {
        violations.push({
          file: relPath,
          rule: rule.label,
          sample: match[0],
        });
      }
    }
  }
}

if (violations.length > 0) {
  console.error(`\n[ZERO-LEAK GATE FAILED] Found ${violations.length} violation(s):`);
  for (const v of violations) {
    console.error(`  - ${v.file}: ${v.rule} -> matched "${v.sample}"`);
  }
  process.exit(1);
}

console.log(
  `[PASS] Zero Process Leakage verified across ${files.length} public surface files${includeDist ? ' (including dist/)' : ''}.`
);
