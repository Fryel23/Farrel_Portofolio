import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const includeDist = process.argv.includes('--dist');

const TEXT_EXTENSIONS = new Set([
  '.astro',
  '.ts',
  '.js',
  '.mjs',
  '.css',
  '.html',
  '.svg',
  '.json',
  '.md',
]);

// Locked baseline files whose comments cannot be altered due to SHA-256 baseline gate;
// we still scan their rendered HTML markup (stripping frontmatter/comments).
const SHA_LOCKED_FILES = new Set([
  'src/components/home/Curtain.astro',
  'src/components/home/HeroCanvas.astro',
]);

function walkDir(dirPath, out = []) {
  if (!fs.existsSync(dirPath)) return out;
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      walkDir(fullPath, out);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (TEXT_EXTENSIONS.has(ext)) {
        out.push(fullPath);
      }
    }
  }
  return out;
}

/**
 * Strip SVG path `d="..."` coordinate sequences and technical CSS/DOM API identifiers
 * so we only match human-visible text, titles, labels, comments, and metadata,
 * without false-positives on SVG `<path d="M0 0V12...">` or `requestAnimationFrame` / `update*` JS identifiers.
 */
function prepareScannableText(raw, relPath) {
  let text = raw;

  if (SHA_LOCKED_FILES.has(relPath)) {
    text = text.replace(/^---[\s\S]*?---/m, '');
    text = text.replace(/<!--[\s\S]*?-->/g, '');
  }

  // Strip SVG path d="..." data and JS SVG path strings so V10/V15/V20 vertical path commands don't look like version tags
  text = text.replace(/\bd\s*=\s*"[^"]*"/g, 'd=""');
  text = text.replace(/\bd\s*=\s*'[^']*'/g, "d=''");
  text = text.replace(/['"`]M\s*\d+[^'"`]*V\d+[^'"`]*['"`]/g, '""');

  // Strip /*! ... */ legal/module banner comments in compiled dist/_astro/*.js bundles
  // and CSS class selectors like .blueprint-corners / .blueprint-grid
  if (relPath.startsWith('dist/_astro/')) {
    text = text.replace(/\/\*![\s\S]*?\*\//g, '');
    text = text.replace(/\.?blueprint-(?:corners|grid|corner|line)[a-z0-9_-]*/gi, '');
  }

  // Strip <script>, <style>, and HTML comments in built dist HTML when scanning dist HTML for visible copy,
  // while still scanning <title>, <meta>, aria-label, alt, data-*, and body text.
  if (relPath.startsWith('dist/') && relPath.endsWith('.html')) {
    text = text.replace(/<!--[\s\S]*?-->/g, '');
    text = text.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
    text = text.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '');
  }

  // Decode HTML entities &amp; so phrase checks match across HTML source too
  text = text.replace(/&amp;/g, '&');

  return text;
}

